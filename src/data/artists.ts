const slug = (name: string) => encodeURIComponent(name.replace(/\s+/g, "_"));
const youtubeSearch = (artist: string, title: string) =>
  `https://www.youtube.com/results?search_query=${encodeURIComponent(`${artist} ${title} official`)}`;

export const artists: Artist[] = profiles.map((p, i) => {
  const price = 30000 + (i % 12) * 12500;
  return {
    id: i + 1,
    name: p.name,
    category: p.category,
    city: p.city,
    price,
    rating: Number((4.3 + (i % 7) * 0.1).toFixed(1)),
    reviews: 60 + i * 11,
    bio: p.bio,
    // The app resolves this Wikipedia page to the artist's current Wikimedia thumbnail.
    image: `https://en.wikipedia.org/api/rest_v1/page/summary/${slug(p.name)}`,
    gallery: [
      `https://en.wikipedia.org/api/rest_v1/page/summary/${slug(p.name)}`,
    ],
    video: youtubeSearch(p.name, p.featuredVideo),
    bookedDates: [
      `2026-10-${String(8 + (i % 10)).padStart(2, "0")}`,
      `2026-11-${String(12 + (i % 10)).padStart(2, "0")}`,
    ],
  };
});

export const artistVideoTitles: Record<
  number,
  { title: string; kind: string }
> = Object.fromEntries(
  profiles.map((p, i) => [
    i + 1,
    { title: p.featuredVideo, kind: p.videoKind },
  ]),
);
